"""Write a route file that sits through the opening with a given cadence.

  python tools/mk_route.py <out> [beats] [wait] [hold]

Lagoon's opening is long and partly scripted: mashing A every 90 frames got to
24 000 frames of dialogue without ever handing over the pad, because a press
arrives while the game is walking Nasir on its own and the text never settles.
A patient cadence (a long wait, one short press) lets scripted movement finish
and the dialogue advance anyway, which is what a player who is reading does.
The route ends with a d-pad sweep and dumps around it, so "control was given"
is a byte comparison against tools/script_play_ctl.txt rather than an opinion.
"""
import sys

def main(argv):
    out = argv[0] if argv else 'tools/script_deep.txt'
    beats = int(argv[1]) if len(argv) > 1 else 90
    wait = int(argv[2]) if len(argv) > 2 else 240
    hold = int(argv[3]) if len(argv) > 3 else 4
    lines = [
        '# Patient intro route: let scripted sequences finish, then take the pad.',
        f'# Generated by tools/mk_route.py {out} {beats} {wait} {hold}.',
        '',
    ]
    for i in range(beats):
        lines.append(f'wait {wait}')
        lines.append(f'press a {hold}')
        if (i + 1) % 10 == 0:
            lines.append('press start 6')
    lines += ['', 'dump wk-a', '', 'press right 40', 'dump wk-b',
              '', 'press down 40', 'dump wk-c', '', 'quit', '']
    open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
    frames = beats * (wait + hold + 1) + (beats // 10) * 7 + 2 * 41
    print(f'{out}: {beats} beats of wait {wait} + press a {hold}, ends near frame {frames}')
    return 0

if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
